// Ember's animations: the frame files in assets/mascot, checked and turned into a play order.
// Rules from the brand notes: frames swap whole (no tweening), 16×16 pixels, one character per pixel.
import { z } from 'zod'

export const mascotStates = [
  'idle',
  'thinking',
  'streaming',
  'success',
  'error',
  'sleeping',
  'loading'
] as const
export type MascotState = (typeof mascotStates)[number]

export const mascotSize = 16

/** One frame: 16 rows of 16 palette keys; '.' is transparent. */
export type Frame = readonly string[]

const frameSchema = z.array(z.string().length(mascotSize)).length(mascotSize).readonly()

// The files are ours, but they're generated by a script and a broken one should fail loudly, not draw garbage.
const fileSchema = z.object({
  state: z.enum(mascotStates),
  ms: z.number().int().positive(),
  /** true: everything loops; false: plays once; a number: `loop-*` frames loop after the `intro-*` ones. */
  loop: z.union([z.boolean(), z.number()]).optional(),
  then: z.enum(mascotStates).optional(),
  pal: z.record(z.string().length(1), z.string().regex(/^#[0-9A-Fa-f]{6}$/)),
  frames: z.record(z.string(), frameSchema)
})

export interface Animation {
  state: MascotState
  /** How long each frame shows. */
  ms: number
  /** Played once, from the start. */
  intro: readonly Frame[]
  /** Repeated after the intro; empty for a one-shot. */
  loop: readonly Frame[]
  /** The state a one-shot hands over to when it ends. */
  then?: MascotState
  palette: Readonly<Record<string, string>>
}

export function parseAnimation(json: unknown): Animation {
  const file = fileSchema.parse(json)
  // Sort by name: JavaScript lists integer-like keys ("10") before others ("09"), so file order can't be trusted.
  const names = Object.keys(file.frames).sort()
  const pick = (prefix: string): Frame[] =>
    names.filter((name) => name.startsWith(prefix)).map((name) => file.frames[name])
  const plain = names.filter((name) => /^\d+$/.test(name)).map((name) => file.frames[name])

  // Named frames (intro-01, loop-01) say what they are; plain numbered ones loop unless the file says loop: false.
  // Other named frames (loading's bar-NN, ready-N) are extras for later.
  const intro = [...pick('intro-'), ...(file.loop === false ? plain : [])]
  const loop = [...(file.loop === false ? [] : plain), ...pick('loop-')]
  if (intro.length + loop.length === 0) throw new Error(`Mascot "${file.state}" has no frames to play`)

  return { state: file.state, ms: file.ms, intro, loop, then: file.then, palette: file.pal }
}

/**
 * The frame to show `tick` frames after the animation started, and whether a one-shot has finished.
 * Pure (no timers), so the play order is tested without waiting.
 */
export function frameAt(animation: Animation, tick: number): { frame: Frame; done: boolean } {
  const { intro, loop } = animation
  if (tick < intro.length) return { frame: intro[tick], done: false }
  if (loop.length > 0) return { frame: loop[(tick - intro.length) % loop.length], done: false }
  return { frame: intro[intro.length - 1], done: true }
}

/** How many frames a one-shot lasts; Infinity for anything that loops. */
export function playLength(animation: Animation): number {
  return animation.loop.length > 0 ? Infinity : animation.intro.length
}

export interface PixelRun {
  x: number
  y: number
  width: number
  color: string
}

/** A frame as horizontal runs of one color, so drawing it takes a few dozen rects instead of 256. */
export function toRuns(frame: Frame, palette: Readonly<Record<string, string>>): PixelRun[] {
  const runs: PixelRun[] = []
  frame.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const key = row[x]
      let end = x + 1
      while (end < row.length && row[end] === key) end++
      const color = palette[key]
      if (color) runs.push({ x, y, width: end - x, color })
      x = end
    }
  })
  return runs
}
